// Validates catalog/tools.json, checks parity with the Tangerine baseline, and regenerates docs/feature-catalog.md.
// Usage: node catalog/build.mjs   (exit code 1 on any failure)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cat = JSON.parse(readFileSync(join(root, "catalog", "tools.json"), "utf8"));
const errors = [];
const fail = (m) => errors.push(m);

// ---- Tangerine baseline (docs/reference/tangerine-features.md) ----
const TG_TOOLS = [
  "image:COMPRESS", "image:METADATA", "image:EDIT", "image:ANNOTATE", "image:ADD BG", "image:CROP", "image:REDACT", "image:CREATE PDF", "image:COLLAGE",
  "video:COMPRESS", "video:METADATA", "video:MUTE", "video:TRIM", "video:CROP", "video:SPEED", "video:SNAPSHOT", "video:SPLIT", "video:JOIN", "video:REDACT",
  "audio:COMPRESS", "audio:METADATA", "audio:NORMALIZE", "audio:VISUALIZE", "audio:TRIM", "audio:CHANNELS", "audio:BLEEP",
  "pdf:COMPRESS", "pdf:METADATA", "pdf:SPLIT", "pdf:ORGANIZE", "pdf:MERGE", "pdf:SAVE IMAGES", "pdf:EXTRACT TEXT",
  "archive:EXTRACT",
  "actions:AIRDROP", "actions:FLOAT", "actions:COPY", "actions:MOVE", "actions:COPY PATH", "actions:TERMINAL",
];
const TG_OUT = {
  image: ["png", "webp", "heic", "tiff", "avif", "bmp", "pdf", "jpg"],
  audio: ["mp3", "m4a", "wav", "flac", "ogg", "opus", "aiff", "wma"],
  video: ["mp4", "mkv", "webm", "avi", "wmv", "gif", "mp3", "mov"],
  pdf: ["docx", "pptx", "xlsx", "jpg", "png", "epub", "txt", "md"],
  document: ["pdf", "txt", "md", "html", "epub", "png", "jpg", "docx"],
  slides: ["pdf", "jpg", "png"],
  spreadsheet: ["xlsx", "ods", "csv", "tsv", "pdf"],
  epub: ["pdf", "docx", "txt", "md", "html"],
  subtitle: ["srt", "vtt", "txt"],
  archive: ["zip", "tar", "gz"],
};
const TG_IN = { image: ["svg"], document: ["rtf"], slides: ["pptx", "ppt"], spreadsheet: ["xls"], archive: ["rar"], video: ["mp4", "mov", "mkv", "webm", "avi", "wmv", "gif"] };
// Windows adaptations: PAGES/Keynote/Numbers are input-only (no open library writes them); documented in docs/plan.md.

// ---- structural validation ----
const ids = new Set();
const cats = new Map(cat.categories.map((c) => [c.id, c]));
for (const t of [...cat.tools, ...cat.actions]) {
  if (ids.has(t.id)) fail(`duplicate id ${t.id}`);
  ids.add(t.id);
  for (const f of ["en", "ar", "engine", "platforms", "phase"]) if (t[f] === undefined) fail(`${t.id}: missing ${f}`);
  if (t.cat && t.cat !== "general" && !cats.has(t.cat)) fail(`${t.id}: unknown category ${t.cat}`);
  // "alsoIn": other input categories whose wheel also offers the tool (e.g. trimming the silence of a video's sound).
  if (t.alsoIn !== undefined) {
    if (!Array.isArray(t.alsoIn) || t.alsoIn.length === 0) fail(`${t.id}: alsoIn must be a non-empty list`);
    else for (const c of t.alsoIn) if (!cats.has(c) || c === t.cat) fail(`${t.id}: alsoIn has an unknown or duplicate category ${c}`);
  }
}
const covered = new Set([...cat.tools, ...cat.actions].map((t) => t.tg).filter(Boolean));
for (const k of TG_TOOLS) if (!covered.has(k)) fail(`parity: Tangerine tool not covered: ${k}`);

// ---- conversions ----
let conversions = 0;
const perCat = [];
for (const c of cat.categories) {
  for (const o of TG_OUT[c.id] ?? []) if (!c.outputs.includes(o)) fail(`parity: ${c.id} missing output ${o}`);
  for (const i of TG_IN[c.id] ?? []) if (!c.inputs.includes(i)) fail(`parity: ${c.id} missing input ${i}`);
  let n = 0;
  for (const i of c.inputs) for (const o of c.outputs) if (i !== o) n++;
  conversions += n;
  perCat.push([c, n]);
}
if (!cat.categories.find((c) => c.id === "pdf").outputs.includes("pptx")) fail("parity: pdf → pptx");

const toolCount = cat.tools.length;
const TARGET = { conversions: 275, tools: 26, actions: 6 };
if (conversions < TARGET.conversions) fail(`conversions ${conversions} < ${TARGET.conversions}`);
if (toolCount < TARGET.tools) fail(`tools ${toolCount} < ${TARGET.tools}`);
if (cat.actions.filter((a) => a.tg).length < TARGET.actions) fail(`file actions < ${TARGET.actions}`);

// ---- generate docs/feature-catalog.md ----
const byPhase = {};
for (const t of [...cat.tools, ...cat.actions]) (byPhase[t.phase] ??= []).push(t);
let md = `# DropFlow feature catalog\n\n> Generated by \`node catalog/build.mjs\` from \`catalog/tools.json\`. Do not edit by hand.\n\n`;
md += `**${conversions}** conversions · **${toolCount}** tools · **${cat.actions.length}** file actions. `;
md += `(Counting method: every distinct input→output format pair within a category. Tangerine advertises 275 / 26 / 6 using its own method; parity is verified per tool and per target below, not by raw count.)\n\n`;
md += `## Conversions\n\n| Category | Inputs | Outputs | Pairs | Phase | Platforms |\n|---|---|---|---|---|---|\n`;
for (const [c, n] of perCat) {
  const late = c.lateOutputs ? ` (${Object.entries(c.lateOutputs).map(([k, v]) => `${k.toUpperCase()}: phase ${v}`).join(", ")})` : "";
  md += `| ${c.en} | ${c.inputs.join(", ")} | ${c.outputs.join(", ")}${late} | ${n} | ${c.phase} | ${c.platforms.join(", ")} |\n`;
}
md += `\nWindows adaptations: Pages / Keynote / Numbers are **input-only**; AirDrop → Windows share sheet; Terminal → Windows Terminal/PowerShell.\n\n`;
md += `## Tools and actions by phase\n\n`;
for (const p of Object.keys(byPhase).sort((a, b) => a - b)) {
  md += `### Phase ${p}\n\n| ID | Tool | الأداة | Engine | Platforms | Tangerine |\n|---|---|---|---|---|---|\n`;
  for (const t of byPhase[p]) md += `| ${t.id} | ${t.en}${t.multi ? " *(multi-file)*" : ""}${t.alsoIn ? ` *(also for ${t.alsoIn.join(", ")})*` : ""} | ${t.ar} | ${t.engine} | ${t.platforms.join(", ")} | ${t.tg ? "✓ " + t.tg : "— (DropFlow extra)"} |\n`;
  md += "\n";
}
writeFileSync(join(root, "docs", "feature-catalog.md"), md);

// Web copy: the landing/web app import this file so they never read outside web/ (Vercel root directory = web).
const webCatalog = {
  stats: { conversions, tools: toolCount, actions: cat.actions.length, categories: cat.categories.length },
  categories: cat.categories,
  tools: cat.tools,
  actions: cat.actions,
};
mkdirSync(join(root, "web", "src", "data"), { recursive: true });
writeFileSync(join(root, "web", "src", "data", "catalog.json"), JSON.stringify(webCatalog, null, 2) + "\n");

// ---- numbers in the READMEs ----
// README.md / README.ar.md write every count as <!--n:key-->value<!--/n--> so the numbers cannot drift from the catalog (the site reads
// the same catalog). Keys: tools, conversions, actions, families, web (tools that run in the browser), cat.<id> (tools per category).
const readmeNumbers = {
  tools: toolCount,
  conversions,
  actions: cat.actions.length,
  families: cat.categories.length,
  web: cat.tools.filter((t) => (t.platforms ?? []).includes("web")).length,
};
for (const t of cat.tools) readmeNumbers[`cat.${t.cat}`] = (readmeNumbers[`cat.${t.cat}`] ?? 0) + 1;
for (const file of ["README.md", "README.ar.md"]) {
  const path = join(root, file);
  const before = readFileSync(path, "utf8");
  const after = before.replace(/<!--n:([\w.]+)-->[^<]*<!--\/n-->/g, (m, key) => {
    if (!(key in readmeNumbers)) { fail(`${file}: unknown number key "${key}"`); return m; }
    return `<!--n:${key}-->${readmeNumbers[key]}<!--/n-->`;
  });
  if (after !== before) writeFileSync(path, after);
}

if (errors.length) {
  console.error("catalog: FAILED\n - " + errors.join("\n - "));
  process.exit(1);
}
console.log(`catalog: OK — ${conversions} conversions, ${toolCount} tools, ${cat.actions.length} actions; all ${TG_TOOLS.length} Tangerine tools and every Tangerine format target covered.`);
