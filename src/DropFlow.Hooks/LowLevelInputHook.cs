using static DropFlow.Hooks.NativeMethods;

namespace DropFlow.Hooks;

/// <summary>
/// Installs WH_MOUSE_LL and WH_KEYBOARD_LL on a dedicated thread with its own message loop (Windows removes hooks
/// whose thread stops pumping messages) and forwards input to a <see cref="DragDetector"/>.
/// Callbacks do no work beyond updating the detector; subscribers to the detector's events must only post elsewhere.
/// </summary>
public sealed class LowLevelInputHook : IDisposable
{
    private readonly DragDetector _detector;
    private readonly HookProc _mouseProc;
    private readonly HookProc _keyboardProc;
    private Thread? _thread;
    private uint _threadId;
    private nint _mouseHook;
    private nint _keyboardHook;

    public LowLevelInputHook(DragDetector detector)
    {
        _detector = detector;
        // Held in fields so the delegates are not garbage-collected while Windows still points at them.
        _mouseProc = MouseCallback;
        _keyboardProc = KeyboardCallback;
    }

    /// <summary>When true, input generated by SendInput (e.g. automation) is ignored.</summary>
    public bool IgnoreInjected { get; set; }

    public static DragDetector CreateSystemDetector() =>
        new(GetSystemMetrics(SM_CXDRAG), GetSystemMetrics(SM_CYDRAG));

    public void Start()
    {
        if (_thread is not null) throw new InvalidOperationException("Hook already started.");
        using var ready = new ManualResetEventSlim();
        Exception? failure = null;

        _thread = new Thread(() =>
        {
            _threadId = GetCurrentThreadId();
            var module = GetModuleHandle(null);
            _mouseHook = SetWindowsHookEx(WH_MOUSE_LL, _mouseProc, module, 0);
            _keyboardHook = SetWindowsHookEx(WH_KEYBOARD_LL, _keyboardProc, module, 0);
            if (_mouseHook == 0 || _keyboardHook == 0)
                failure = new System.ComponentModel.Win32Exception(System.Runtime.InteropServices.Marshal.GetLastWin32Error());
            ready.Set();
            if (failure is not null) return;

            while (GetMessage(out _, 0, 0, 0) > 0) { /* the loop only keeps the hooks alive */ }

            UnhookWindowsHookEx(_mouseHook);
            UnhookWindowsHookEx(_keyboardHook);
        })
        {
            IsBackground = true,
            Name = "DropFlow.InputHook",
        };
        _thread.Start();
        ready.Wait();
        if (failure is not null) throw failure;
    }

    private nint MouseCallback(int nCode, nint wParam, nint lParam)
    {
        if (nCode >= 0)
        {
            try
            {
                var data = System.Runtime.InteropServices.Marshal.PtrToStructure<MSLLHOOKSTRUCT>(lParam);
                if (!(IgnoreInjected && (data.flags & LLMHF_INJECTED) != 0))
                {
                    switch ((int)wParam)
                    {
                        case WM_LBUTTONDOWN: _detector.OnMouseDown(data.pt.X, data.pt.Y); break;
                        case WM_MOUSEMOVE: _detector.OnMouseMove(data.pt.X, data.pt.Y); break;
                        case WM_LBUTTONUP: _detector.OnMouseUp(data.pt.X, data.pt.Y); break;
                    }
                }
            }
            catch { /* never let an exception escape a hook callback */ }
        }
        return CallNextHookEx(_mouseHook, nCode, wParam, lParam);
    }

    private nint KeyboardCallback(int nCode, nint wParam, nint lParam)
    {
        if (nCode >= 0)
        {
            try
            {
                var data = System.Runtime.InteropServices.Marshal.PtrToStructure<KBDLLHOOKSTRUCT>(lParam);
                if (!(IgnoreInjected && (data.flags & LLKHF_INJECTED) != 0))
                {
                    switch ((int)wParam)
                    {
                        case WM_KEYDOWN or WM_SYSKEYDOWN: _detector.OnKeyDown((int)data.vkCode); break;
                        case WM_KEYUP or WM_SYSKEYUP: _detector.OnKeyUp((int)data.vkCode); break;
                    }
                }
            }
            catch { /* never let an exception escape a hook callback */ }
        }
        // The spike observes only; it never swallows keys. Whether Alt/Shift taps disturb Explorer is a Phase 0 finding.
        return CallNextHookEx(_keyboardHook, nCode, wParam, lParam);
    }

    public void Dispose()
    {
        if (_thread is null) return;
        PostThreadMessage(_threadId, WM_QUIT, 0, 0);
        _thread.Join(TimeSpan.FromSeconds(2));
        _thread = null;
    }
}
